"""Write COMMODITIES.md: every commodity name in the downloaded price data and how it is used.

Reads data/raw/ogd_prices.parquet (cached API pages, consolidated), out/selection.json
(pilot series) and out/metrics_extended.json (good-data rule and its counts), so the
file can be regenerated at any time and never needs hand edits.

Usage (from project root):
    uv run python -I -X utf8 src/commodities.py
"""

from __future__ import annotations

import datetime as dt
import json
import re
from pathlib import Path

import polars as pl

from apa import clean, paths

ROOT = Path(__file__).resolve().parents[1]
RESOURCE = "35985678-0d79-46b4-9ed6-6f13308a1d24"


def _num(v: int) -> str:
    return f"{int(v):,}"


def _date(d) -> str:
    return dt.date.fromisoformat(str(d)[:10]).strftime("%d %b %Y").lstrip("0")


def _join(names: list[str]) -> str:
    return ", ".join(names[:-1]) + " and " + names[-1] if len(names) > 1 else names[0]


def main() -> None:
    sel = json.loads((paths.OUT / "selection.json").read_text(encoding="utf-8"))
    ext = json.loads((paths.OUT / "metrics_extended.json").read_text(encoding="utf-8"))
    pilot = sorted({p["commodity"] for p in sel["pairs"]})
    extended = ext["ext_commodities"]
    rule = ext["rule"]
    cov = {r["commodity"]: r for r in ext["commodity_coverage"]}
    end = dt.date.fromisoformat(ext["end_week"])
    w3 = end - dt.timedelta(weeks=rule["window_3y_weeks"] - 1)
    w1 = end - dt.timedelta(weeks=rule["window_1y_weeks"] - 1)

    raw = pl.scan_parquet(paths.RAW_PARQUET).with_columns(
        pl.col("state").str.strip_chars(), pl.col("commodity").str.strip_chars(), clean.market_key().alias("market_key"))
    retrieved = raw.select(pl.col("retrieved_at").max()).collect().item()[:10]
    per = (
        raw.group_by("state", "commodity")
        .agg(pl.len().alias("rows"), pl.col("date").min().alias("first"), pl.col("date").max().alias("last"),
             pl.col("market_key").n_unique().alias("markets"))
        .collect()
    )
    assam = per.filter(pl.col("state") == "Assam")
    others = per.filter(pl.col("state") != "Assam").sort("state", "commodity")
    n_assam_rows = int(assam.get_column("rows").sum())
    a_first = assam.get_column("first").min()
    a_last = assam.get_column("last").max()
    o_states = sorted(others.get_column("state").unique().to_list())
    o_comms = sorted(others.get_column("commodity").unique().to_list())
    o_recent = 100 * raw.filter((pl.col("state") != "Assam") & (pl.col("date") >= dt.date(2016, 1, 1))).select(
        pl.len()).collect().item() / int(others.get_column("rows").sum())

    # names that differ only by spacing before a bracket (likely renamed at the Agmarknet 2.0 migration)
    def norm(s: str) -> str:
        return re.sub(r"\s+", " ", re.sub(r"\s+\(", "(", s)).strip().lower()

    groups: dict[str, list[str]] = {}
    for c in assam.get_column("commodity").to_list():
        groups.setdefault(norm(c), []).append(c)
    twin = {c: [o for o in g if o != c] for g in groups.values() if len(g) > 1 for c in g}
    assert not any(c in twin for c in extended), "a modelled commodity has a second published name"

    def use(c: str) -> tuple[int, str]:
        r = cov.get(c, {"weeks_3y": 0, "weeks_1y": 0})
        if c in pilot:
            return 0, "Pilot: forecasts and advisory; advisory-model training; extended test"
        if c in extended:
            return 1, "Advisory-model training; extended accuracy test"
        if r["weeks_3y"] == 0 and r["weeks_1y"] == 0:
            return 3, "Not modelled: no price in the last 156 weeks"
        why = []
        if r["weeks_3y"] < rule["min_weeks_3y"]:
            why.append(f"under {_num(rule['min_weeks_3y'])} market-weeks in 156 weeks")
        if r["weeks_1y"] < rule["min_weeks_1y"]:
            why.append(f"under {_num(rule['min_weeks_1y'])} in the last 52")
        return 2, "Not modelled: " + "; ".join(why)

    rows = []
    for r in assam.iter_rows(named=True):
        c = r["commodity"]
        k, u = use(c)
        cv = cov.get(c, {"weeks_3y": 0, "weeks_1y": 0})
        rows.append((k, -cv["weeks_3y"], -r["rows"], c, r, cv, u))
    rows.sort(key=lambda t: t[:4])

    L = [
        "# Commodities in the downloaded price data",
        "",
        f"Generated by `src/commodities.py` from `data/raw/ogd_prices.parquet`: Agmarknet daily market prices "
        f"(Directorate of Marketing and Inspection) from the data.gov.in OGD API, resource `{RESOURCE}`, retrieved "
        f"{_date(retrieved)}. Do not edit by hand; rerun the script (it is part of `src/pipeline.py`).",
        "",
        "## What was downloaded",
        "",
        f"- **Assam:** all commodities, {_num(n_assam_rows)} daily price rows from {_date(a_first)} to "
        f"{_date(a_last)}, under {len(assam)} commodity names as published.",
        f"- **Neighbouring States** ({_join(o_states)}): the three pilot commodities only ({_join(o_comms)}), "
        f"{_num(int(others.get_column('rows').sum()))} rows, {o_recent:.0f}% of them since 2016. They feed the seasonal "
        f"profiles, the stress test and the model set before testing.",
        "",
        "## How the commodities are used",
        "",
        f"- **Pilot (forecasts and Hold / Sell / Store advisory):** {_join(pilot)}. These are the commodities of the three "
        f"best-reported Assam market series (rule in `out/selection.json`); every Assam market of these commodities is forecast.",
        f"- **Good-data commodities ({len(extended)}):** {_join(extended)}. They are the training data of the advisory model "
        f"(chosen by the applicant after the 12-month test) and are scored in the extended accuracy test. Rule for good data, fixed before any "
        f"model was run on them and based on coverage only: at least {_num(rule['min_weeks_3y'])} market-weeks with a "
        f"price in the last {rule['window_3y_weeks']} complete weeks ({_date(w3)} to the week of {_date(end)}) and at least "
        f"{_num(rule['min_weeks_1y'])} in the last {rule['window_1y_weeks']} (the test year, from {_date(w1)}). A market-week "
        f"is one market reporting a price in one week (main variety). Assam markets only. Results: `out/metrics_extended.json` "
        f"and the Proof of Work PDF.",
        "- **Not modelled:** all other names; the table gives the reason.",
        "",
        "Names marked † appear twice, differing only by a space before a bracket; they are probably the same commodity "
        "renamed at the Agmarknet 2.0 migration (December 2025). They are listed as published and were not merged; "
        "none of them is in the modelled sets.",
        "",
        "## Assam",
        "",
        "| Commodity (as published) | Rows | First date | Last date | Markets | Market-weeks, last 156 wk | Market-weeks, last 52 wk | Use |",
        "|---|--:|---|---|--:|--:|--:|---|",
    ]
    for _k, _w, _r, c, r, cv, u in rows:
        name = c.replace("|", "/") + (" †" if c in twin else "")
        L.append(f"| {name} | {_num(r['rows'])} | {_date(r['first'])} | {_date(r['last'])} | {r['markets']} | "
                 f"{_num(cv['weeks_3y'])} | {_num(cv['weeks_1y'])} | {u} |")
    L += [
        "",
        "## Neighbouring States",
        "",
        "| State | Commodity | Rows | First date | Last date | Markets |",
        "|---|---|--:|---|---|--:|",
    ]
    for r in others.iter_rows(named=True):
        L.append(f"| {r['state']} | {r['commodity']} | {_num(r['rows'])} | {_date(r['first'])} | {_date(r['last'])} | {r['markets']} |")
    L += ["", "Rows are daily price records. Markets are counted after harmonising market names (`src/apa/clean.py`).", ""]
    (ROOT / "COMMODITIES.md").write_text("\n".join(L), encoding="utf-8")
    print(f"COMMODITIES.md written: {len(assam)} Assam names, {len(others)} neighbour-State rows")


if __name__ == "__main__":
    main()
